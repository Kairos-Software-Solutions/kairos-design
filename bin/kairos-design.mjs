#!/usr/bin/env node
/**
 * kairos-design — emit the CSS artifacts into a surface that cannot import them.
 *
 * Most apps never run this. A bundled app depends on the package and imports
 * it, and the bundler inlines the bytes into the app's own stylesheet at build
 * time:
 *
 *   @import "kairos-design/tokens.css";
 *   import { Button } from 'kairos-design/react';
 *
 * That reaches first paint with no network request and no copy in the repo,
 * which is what the old `sync` was really trying to buy.
 *
 * Three surfaces cannot import anything. Uptime serves a static `public/` with
 * no bundler, Card is a single HTML file that inlines its CSS, and Mailclient
 * is a Roundcube skin. They run this from a build script and gitignore what it
 * writes.
 *
 * What it writes is a build artifact, not source. That is the point, and it is
 * why `check` no longer exists: a file that is only ever produced by a build,
 * from a version fixed in package.json, cannot quietly disagree with the
 * package. There is nothing left to verify.
 *
 *   kairos-design emit [--app <dir>] [--from <dir>] [--dry-run]
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CONFIG = 'kairos-design.json';

/**
 * The artifacts are whatever `dist/` holds. Derived rather than listed,
 * because a hand-maintained mirror of a directory is a second place to forget:
 * the old array had to be edited in the same commit as every new component,
 * and a component missing from it was invisible to every consuming app.
 */
function artifacts(root) {
  const base = join(root, 'dist');
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir).sort()) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.(css|ts|tsx)$/.test(entry)) found.push(relative(base, full).split('\\').join('/'));
    }
  };
  walk(base);
  return found;
}

/* A block comment, because it has to be valid in both CSS and TypeScript. */
const GENERATED = (artifact, version) =>
  `/* Generated by kairos-design ${version} from ${artifact}. Do not edit, and do\n` +
  `   not commit: re-running the build overwrites it. Change it in the\n` +
  `   kairos-design package and release a version. */\n`;

class Fail extends Error {}

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') args.dryRun = true;
    else if (a.startsWith('--')) args[a.slice(2)] = argv[++i];
    else args._.push(a);
  }
  return args;
}

/**
 * Where the artifacts come from.
 *
 * Normally this file is running from inside the installed package, so the
 * answer is "beside me" and there is nothing to configure or keep in sync. The
 * old sibling-checkout search is gone with the clone-it-yourself workflow that
 * needed it; `--from` remains for developing the package against a live app.
 */
function findSource(explicit) {
  const own = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  for (const c of [explicit, own].filter(Boolean)) {
    if (existsSync(join(c, 'dist', 'tokens.css'))) return resolve(c);
  }
  throw new Fail(
    `No dist/ in ${explicit}.\nPass --from <dir> pointing at a kairos-design checkout or install.`
  );
}

function version(root) {
  try {
    return JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version ?? 'unknown';
  } catch {
    return 'unknown';
  }
}

function readConfig(appDir, known) {
  const path = join(appDir, CONFIG);
  if (!existsSync(path)) {
    throw new Fail(
      `No ${CONFIG} in ${appDir}.\n\n` +
        'Only a surface with no bundler needs one. If this app builds with Next,\n' +
        'Vite, or anything else that resolves imports, delete the emit step and\n' +
        'import the package instead:\n\n' +
        '  @import "kairos-design/tokens.css";\n\n' +
        'Otherwise create one naming where each artifact should land:\n\n' +
        JSON.stringify(
          { targets: [{ artifact: 'tokens.css', path: 'public/kairos-tokens.css' }] },
          null,
          2
        ) +
        '\n\nUse "inline": "<marker>" instead of a plain copy to write into a region\n' +
        'of an existing file, which is what a single-file app needs to keep its\n' +
        'tokens inline for first paint.'
    );
  }

  let config;
  try {
    config = JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    throw new Fail(`${CONFIG} is not valid JSON: ${e.message}`);
  }

  if (!Array.isArray(config.targets) || config.targets.length === 0) {
    throw new Fail(`${CONFIG} has no targets. Add at least one.`);
  }

  for (const t of config.targets) {
    if (!known.includes(t.artifact)) {
      throw new Fail(
        `${CONFIG} names an unknown artifact "${t.artifact}".\n` +
          `Known artifacts: ${known.join(', ')}`
      );
    }
    if (!t.path || isAbsolute(t.path)) {
      throw new Fail(
        `${CONFIG} target for "${t.artifact}" needs a relative "path" inside the app.`
      );
    }
    if (t.artifact.startsWith('react/') || t.artifact.startsWith('format/')) {
      throw new Fail(
        `${CONFIG} asks to emit "${t.artifact}", which is TypeScript.\n\n` +
          'A surface that can compile TypeScript can also resolve an import, so it\n' +
          "should depend on the package rather than copy out of it:\n\n" +
          `  import { Button } from 'kairos-design/react';\n\n` +
          'Emit is for CSS reaching a surface that has no bundler at all.'
      );
    }
  }

  return config;
}

const markers = (name) => ({
  begin: `/* kairos-design:${name} begin */`,
  end: `/* kairos-design:${name} end */`,
});

/** The bytes this target should hold, given the package's current artifact. */
function desired(root, target, v) {
  const source = readFileSync(join(root, 'dist', target.artifact), 'utf8');
  return GENERATED(target.artifact, v) + source;
}

/** What the target holds today: the whole file, or the marked region of one. */
function actual(appDir, target) {
  const path = join(appDir, target.path);
  if (!existsSync(path)) return null;
  const file = readFileSync(path, 'utf8');
  if (!target.inline) return file;

  const { begin, end } = markers(target.inline);
  const from = file.indexOf(begin);
  const to = file.indexOf(end);
  if (from === -1 || to === -1 || to < from) return null;
  return file.slice(from + begin.length, to).replace(/^\n/, '');
}

function write(appDir, target, content, dryRun) {
  const path = join(appDir, target.path);

  if (!target.inline) {
    if (!dryRun) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
    return;
  }

  const { begin, end } = markers(target.inline);
  if (!existsSync(path)) {
    throw new Fail(
      `${target.path} does not exist, and an inline target cannot create it.\n` +
        `Add the markers to the file first:\n\n  ${begin}\n  ${end}`
    );
  }
  const file = readFileSync(path, 'utf8');
  const from = file.indexOf(begin);
  const to = file.indexOf(end);
  if (from === -1 || to === -1) {
    throw new Fail(
      `${target.path} is missing the "${target.inline}" markers. Add both, in order:\n\n` +
        `  ${begin}\n  ${end}`
    );
  }
  if (to < from) {
    throw new Fail(`${target.path} has the "${target.inline}" end marker before its begin marker.`);
  }
  const next = file.slice(0, from + begin.length) + '\n' + content + file.slice(to);
  if (!dryRun) writeFileSync(path, next);
}

function emit(appDir, root, dryRun) {
  const v = version(root);
  const config = readConfig(appDir, artifacts(root));

  let changed = 0;
  for (const target of config.targets) {
    const want = desired(root, target, v);
    const have = actual(appDir, target);

    if (have === want) {
      console.log(`  = ${target.path}`);
      continue;
    }
    write(appDir, target, want, dryRun);
    console.log(
      `  ${have === null ? '+' : 'M'} ${target.path}${target.inline ? ` (${target.inline})` : ''}`
    );
    changed++;
  }

  console.log(
    dryRun
      ? `\n${changed} file(s) would change. kairos-design ${v}.`
      : `\n${changed} file(s) written. kairos-design ${v}.`
  );
  return 0;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const command = args._[0];

  if (!command || command === 'help' || args.help !== undefined) {
    console.log(
      [
        'kairos-design — emit the CSS artifacts into a surface with no bundler',
        '',
        '  emit   write each artifact named in kairos-design.json',
        '',
        'Options',
        '  --app <dir>    the app to write into (default: the working directory)',
        '  --from <dir>   a kairos-design checkout (default: the installed package)',
        '  --dry-run      report what emit would change, write nothing',
        '',
        'A bundled app does not need this. Import the package instead:',
        '',
        '  @import "kairos-design/tokens.css";',
      ].join('\n')
    );
    return 0;
  }

  if (command === 'sync' || command === 'check') {
    throw new Fail(
      `\`${command}\` is gone as of 0.2.0.\n\n` +
        'The design system is a package now, so an app depends on a version in\n' +
        'package.json instead of vendoring a copy and checking it for drift.\n\n' +
        '  npm install kairos-design\n' +
        '  @import "kairos-design/tokens.css";\n\n' +
        'A surface with no bundler runs `kairos-design emit` from its build and\n' +
        'gitignores the output. Delete kairos-design.lock.json either way.\n' +
        'See docs/adoption.md.'
    );
  }

  const appDir = resolve(args.app ?? process.cwd());
  const root = findSource(args.from);

  if (root === appDir) throw new Fail('kairos-design cannot emit into itself. Pass --app <dir>.');

  if (command === 'emit') {
    console.log(`kairos-design emit`);
    console.log(`  app  ${appDir}\n`);
    return emit(appDir, root, args.dryRun === true);
  }

  throw new Fail(`Unknown command "${command}". Try \`kairos-design help\`.`);
}

try {
  process.exit(main());
} catch (e) {
  if (e instanceof Fail) {
    console.error(`\n${e.message}\n`);
    process.exit(1);
  }
  throw e;
}
