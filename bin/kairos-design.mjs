#!/usr/bin/env node
/**
 * kairos-design — vendor the Kairos design system into an app.
 *
 * The registry is distributed by copying, not by resolving a package. Two
 * reasons, and both are load-bearing:
 *
 *   Tokens have to apply before first paint. A stylesheet fetched from a CDN
 *   in the critical path buys a flash of the wrong theme in exchange for
 *   saving a file copy.
 *
 *   Paykit and Mailkit build with `build: .` and `COPY . .`, so the Docker
 *   build context is the app directory and `npm ci` runs with no GitHub
 *   credentials. Anything resolved at build time would need BuildKit SSH
 *   forwarding in every Dockerfile. Copies need nothing.
 *
 * The cost of copying is that a copy goes stale silently, so `check` exists
 * and belongs in CI.
 *
 *   kairos-design sync  [--app <dir>] [--registry <dir>] [--dry-run]
 *   kairos-design check [--app <dir>] [--registry <dir>]
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';

const CONFIG = 'kairos-design.json';
const LOCK = 'kairos-design.lock.json';
const ARTIFACTS = [
  'tokens.css',
  'base.css',
  'kairos.css',
  'format/money.ts',
  'format/dates.ts',
  'react/index.ts',
  'react/Button.tsx',
  'react/StateChip.tsx',
  'react/Segmented.tsx',
  'react/Field.tsx',
  'react/Banner.tsx',
  'react/EmptyState.tsx',
  'react/SortHeader.tsx',
  'react/Dialog.tsx',
  'react/ConfirmDialog.tsx',
  'react/Toast.tsx',
  'react/Panel.tsx',
  'react/theme.tsx',
];

/* A block comment, because it has to be valid in both CSS and TypeScript. */
const GENERATED = (artifact) =>
  `/* Generated by kairos-design from dist/${artifact}. Do not edit here.\n` +
  `   Edit it in the kairos-design repo and re-run \`kairos-design sync\`. */\n`;

class Fail extends Error {}

const sha256 = (s) => 'sha256:' + createHash('sha256').update(s).digest('hex');

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') args.dryRun = true;
    else if (a.startsWith('--')) args[a.slice(2)] = argv[++i];
    else args._.push(a);
  }
  return args;
}

/**
 * Where the registry lives. Explicit flag, then the environment, then a
 * sibling checkout — which is the layout a developer gets by cloning both
 * repos into one directory, and the only one that needs no configuration.
 */
function findRegistry(explicit) {
  const candidates = [
    explicit,
    process.env.KAIROS_DESIGN,
    resolve(process.cwd(), '..', 'kairos-design'),
    resolve(process.cwd(), '..', '..', 'kairos-design'),
    resolve(process.cwd(), '..', '..', '..', 'kairos-design'),
  ].filter(Boolean);

  for (const c of candidates) {
    if (existsSync(join(c, 'dist', 'tokens.css'))) return resolve(c);
  }
  throw new Fail(
    'Could not find the kairos-design registry.\n' +
      'Clone it beside this app, or pass --registry <dir>, or set KAIROS_DESIGN.\n' +
      '  git clone git@github.com:Kairos-Software-Solutions/kairos-design.git'
  );
}

/** The registry's own version, for the lockfile. Untagged checkouts are fine. */
function registryVersion(root) {
  const git = (args, fallback) => {
    try {
      return execFileSync('git', ['-C', root, ...args], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
    } catch {
      return fallback;
    }
  };
  const dirty = git(['status', '--porcelain'], '') !== '';
  return {
    describe: git(['describe', '--tags', '--always'], 'unknown'),
    commit: git(['rev-parse', 'HEAD'], 'unknown'),
    ...(dirty ? { dirty: true } : {}),
  };
}

function readConfig(appDir) {
  const path = join(appDir, CONFIG);
  if (!existsSync(path)) {
    throw new Fail(
      `No ${CONFIG} in ${appDir}.\n\n` +
        'Create one naming where each artifact should land:\n\n' +
        JSON.stringify(
          {
            targets: [
              { artifact: 'tokens.css', path: 'src/app/kairos-tokens.css' },
              { artifact: 'kairos.css', path: 'src/app/kairos.css' },
            ],
          },
          null,
          2
        ) +
        '\n\nUse "inline": "<marker>" instead of a plain copy to write into a\n' +
        'region of an existing file, which is what a single-file app needs to\n' +
        'keep its tokens inline for first paint.'
    );
  }

  let config;
  try {
    config = JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    throw new Fail(`${CONFIG} is not valid JSON: ${e.message}`);
  }

  if (!Array.isArray(config.targets) || config.targets.length === 0) {
    throw new Fail(`${CONFIG} has no targets. Add at least one.`);
  }

  for (const t of config.targets) {
    if (!ARTIFACTS.includes(t.artifact)) {
      throw new Fail(
        `${CONFIG} names an unknown artifact "${t.artifact}".\n` +
          `Known artifacts: ${ARTIFACTS.join(', ')}`
      );
    }
    if (!t.path || isAbsolute(t.path)) {
      throw new Fail(
        `${CONFIG} target for "${t.artifact}" needs a relative "path" inside the app.`
      );
    }
  }

  /* The React components import each other by relative path — ConfirmDialog
     imports ./Dialog and ./Button — so splitting them across directories
     produces a module-not-found at build time, a long way from the config that
     caused it. Catch it here, where the reason is still in view. */
  const reactDirs = new Map();
  for (const t of config.targets) {
    if (!t.artifact.startsWith('react/')) continue;
    const dir = dirname(t.path);
    if (!reactDirs.has(dir)) reactDirs.set(dir, []);
    reactDirs.get(dir).push(t.artifact);
  }
  if (reactDirs.size > 1) {
    const listed = [...reactDirs]
      .map(([dir, artifacts]) => `  ${dir || '.'}  ${artifacts.join(', ')}`)
      .join('\n');
    throw new Fail(
      `${CONFIG} spreads the React components across ${reactDirs.size} directories:\n\n` +
        listed +
        '\n\nThey import each other by relative path, so they all have to land in one\n' +
        'directory. Point every react/ target at the same one.'
    );
  }

  return config;
}

const markers = (name) => ({
  begin: `/* kairos-design:${name} begin */`,
  end: `/* kairos-design:${name} end */`,
});

/** The bytes this target should hold, given the registry's current artifact. */
function desired(registryRoot, target) {
  const source = readFileSync(join(registryRoot, 'dist', target.artifact), 'utf8');
  return GENERATED(target.artifact) + source;
}

/** What the target holds today: the whole file, or the marked region of one. */
function actual(appDir, target) {
  const path = join(appDir, target.path);
  if (!existsSync(path)) return null;
  const file = readFileSync(path, 'utf8');
  if (!target.inline) return file;

  const { begin, end } = markers(target.inline);
  const from = file.indexOf(begin);
  const to = file.indexOf(end);
  if (from === -1 || to === -1 || to < from) return null;
  return file.slice(from + begin.length, to).replace(/^\n/, '');
}

function write(appDir, target, content, dryRun) {
  const path = join(appDir, target.path);

  if (!target.inline) {
    if (!dryRun) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
    return;
  }

  const { begin, end } = markers(target.inline);
  if (!existsSync(path)) {
    throw new Fail(
      `${target.path} does not exist, and an inline target cannot create it.\n` +
        `Add the markers to the file first:\n\n  ${begin}\n  ${end}`
    );
  }
  const file = readFileSync(path, 'utf8');
  const from = file.indexOf(begin);
  const to = file.indexOf(end);
  if (from === -1 || to === -1) {
    throw new Fail(
      `${target.path} is missing the "${target.inline}" markers. Add both, in order:\n\n` +
        `  ${begin}\n  ${end}`
    );
  }
  if (to < from) {
    throw new Fail(`${target.path} has the "${target.inline}" end marker before its begin marker.`);
  }
  const next = file.slice(0, from + begin.length) + '\n' + content + file.slice(to);
  if (!dryRun) writeFileSync(path, next);
}

function sync(appDir, registryRoot, dryRun) {
  const config = readConfig(appDir);
  const version = registryVersion(registryRoot);
  const lock = { registry: version, syncedAt: new Date().toISOString(), targets: {} };

  let changed = 0;
  for (const target of config.targets) {
    const want = desired(registryRoot, target);
    const have = actual(appDir, target);
    lock.targets[target.path] = sha256(want);

    if (have === want) {
      console.log(`  = ${target.path}`);
      continue;
    }
    write(appDir, target, want, dryRun);
    console.log(`  ${have === null ? '+' : 'M'} ${target.path}${target.inline ? ` (${target.inline})` : ''}`);
    changed++;
  }

  if (!dryRun) writeFileSync(join(appDir, LOCK), JSON.stringify(lock, null, 2) + '\n');

  const at = version.describe + (version.dirty ? ' (uncommitted changes)' : '');
  console.log(
    dryRun
      ? `\n${changed} file(s) would change. Registry at ${at}.`
      : `\n${changed} file(s) written. Registry at ${at}.`
  );
  if (version.dirty) {
    console.log(
      'The registry checkout has uncommitted changes, so this sync is not reproducible.'
    );
  }
  return 0;
}

/**
 * Two failures, and they need different fixes, so they are reported
 * separately: a vendored file edited in place is lost work waiting to happen,
 * and a registry that has moved ahead is just a re-sync.
 */
function check(appDir, registryRoot) {
  const config = readConfig(appDir);
  const lockPath = join(appDir, LOCK);
  if (!existsSync(lockPath)) {
    console.error(`No ${LOCK}. Run \`kairos-design sync\` first.`);
    return 1;
  }
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'));

  const edited = [];
  const behind = [];

  for (const target of config.targets) {
    const want = desired(registryRoot, target);
    const have = actual(appDir, target);
    const locked = lock.targets?.[target.path];

    if (have === null) {
      edited.push(`${target.path} — missing`);
      continue;
    }
    const haveHash = sha256(have);
    if (locked && haveHash !== locked) edited.push(`${target.path} — edited since the last sync`);
    if (sha256(want) !== haveHash && (!locked || haveHash === locked)) behind.push(target.path);
  }

  if (!edited.length && !behind.length) {
    console.log(`Up to date with the registry at ${lock.registry?.describe ?? 'unknown'}.`);
    return 0;
  }

  if (edited.length) {
    console.error('Vendored files were edited in place:');
    for (const e of edited) console.error(`  ${e}`);
    console.error('\nThese are generated. Move the change into the kairos-design repo,');
    console.error('then re-run `kairos-design sync` here. Editing the copy loses the');
    console.error('change on the next sync and hides it from every other app.\n');
  }
  if (behind.length) {
    console.error('Behind the registry:');
    for (const b of behind) console.error(`  ${b}`);
    console.error('\nRun `kairos-design sync`.\n');
  }
  return 1;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const command = args._[0];

  if (!command || command === 'help' || args.help !== undefined) {
    console.log(
      [
        'kairos-design — vendor the Kairos design system into an app',
        '',
        '  sync   copy the registry artifacts in and write the lockfile',
        '  check  fail if a copy was edited in place or has fallen behind',
        '',
        'Options',
        '  --app <dir>       the app to sync (default: the working directory)',
        '  --registry <dir>  the kairos-design checkout (default: a sibling, or $KAIROS_DESIGN)',
        '  --dry-run         report what sync would change, write nothing',
      ].join('\n')
    );
    return 0;
  }

  const appDir = resolve(args.app ?? process.cwd());
  const registryRoot = findRegistry(args.registry);

  if (registryRoot === appDir) {
    throw new Fail('The registry cannot sync into itself. Pass --app <dir>.');
  }

  // A sibling checkout reads well as `../kairos-design`. Anything that has to
  // climb further is clearer written out in full.
  const rel = relative(appDir, registryRoot);
  const shown = rel && !rel.startsWith('../..') ? rel : registryRoot;

  console.log(`kairos-design ${command}`);
  console.log(`  app      ${appDir}`);
  console.log(`  registry ${shown}\n`);

  if (command === 'sync') return sync(appDir, registryRoot, args.dryRun === true);
  if (command === 'check') return check(appDir, registryRoot);

  throw new Fail(`Unknown command "${command}". Try \`kairos-design help\`.`);
}

try {
  process.exit(main());
} catch (e) {
  if (e instanceof Fail) {
    console.error(`\n${e.message}\n`);
    process.exit(1);
  }
  throw e;
}
